const dicts: Record<Language, Dict> = { English: en, 'తెలుగు': te, 'हिन्दी': hi };

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  const dict = dicts[lang] ?? en;
  let str = dict[key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) str = str.replace(`{${k}}`, String(v));
  return str;
}

export type T = (key: string, params?: Record<string, string | number>) => string;
export function makeT(lang: Language): T { return (key, params) => translate(lang, key, params); }

