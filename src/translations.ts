export type LanguageCode = 'en' | 'te' | 'hi';

const codeToLanguage: Record<LanguageCode, Language> = {
  en: 'English',
  te: 'తెలుగు',
  hi: 'हिन्दी',
};

const languageToCode: Record<Language, LanguageCode> = {
  English: 'en',
  'తెలుగు': 'te',
  'हिन्दी': 'hi',
};

export function languageFromCode(code: string): Language {
  const normalized = code?.toLowerCase();
  if (normalized === 'te') return 'తెలుగు';
  if (normalized === 'hi') return 'हिन्दी';
  return 'English';
}

export function codeFromLanguage(lang: Language): LanguageCode {
  return languageToCode[lang] ?? 'en';
}
